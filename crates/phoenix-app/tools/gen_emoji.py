import sys, re
src, out = sys.argv[1], sys.argv[2]
seqs_out = sys.argv[3] if len(sys.argv) > 3 else None
MAX = (16, 0)
seqs = []
CAT = {"Smileys & Emotion":0,"People & Body":0,"Animals & Nature":1,"Food & Drink":2,"Activities":3,"Travel & Places":4,"Objects":5,"Symbols":6,"Flags":7}
ALIAS = {"grinning face":"grinning","face with tears of joy":"joy","thumbs up":"thumbsup +1","thumbs down":"thumbsdown -1","red heart":"heart","smiling face with smiling eyes":"blush","grinning face with smiling eyes":"smile","grinning face with big eyes":"smiley","loudly crying face":"sob","fire":"fire","clapping hands":"clap","folded hands":"pray","thinking face":"thinking","eyes":"eyes","skull":"skull","party popper":"tada","winking face":"wink","smiling face with heart-eyes":"heart_eyes","rolling on the floor laughing":"rofl","ok hand":"ok_hand","waving hand":"wave","pile of poo":"poop","face with rolling eyes":"rolling_eyes","pleading face":"pleading","check mark button":"white_check_mark","cross mark":"x","hundred points":"100","sparkles":"sparkles","flexed biceps":"muscle","slightly smiling face":"slight_smile","upside-down face":"upside_down","neutral face":"neutral_face","angry face":"angry","crying face":"cry","sleeping face":"sleeping","partying face":"partying_face","rocket":"rocket","star":"star","sunglasses":"sunglasses","smiling face with sunglasses":"sunglasses","raising hands":"raised_hands","person shrugging":"shrug","person facepalming":"facepalm"}
groups, entries = None, []
seen_tone = set()
group = None
for line in open(src, encoding="utf-8"):
    if line.startswith("# group:"):
        group = line.split(":",1)[1].strip(); continue
    if not line.strip() or line.startswith("#"): continue
    m = re.match(r"^([0-9A-F ]+?)\s*;\s*(\S+)\s*#\s*(\S+)\s+E(\d+)\.(\d+)\s+(.*)$", line.rstrip("\n"))
    if not m: continue
    cps, status, emo, maj, mnr, name = m.groups()
    if status != "fully-qualified" or group not in CAT: continue
    if (int(maj), int(mnr)) > MAX: continue
    seqs.append(emo)
    cpl = cps.split()
    if any(c in ("1F3FB","1F3FC","1F3FD","1F3FE","1F3FF") for c in cpl):
        base = name.split(":")[0].strip()
        seen_tone.add(base); continue
    entries.append((emo, name, CAT[group]))
def code(name):
    s = name.lower().replace("flag: ","flag_").replace("’","").replace("'","")
    s = re.sub(r"[^a-z0-9+\-]+","_",s).strip("_")
    return s
def esc(s): return s.replace("\\","\\\\").replace('"','\\"')
with open(out,"w",encoding="utf-8") as f:
    f.write("// @generated by crates/phoenix-app/tools/gen_emoji.py from Unicode emoji-test.txt (entries <= E16.0).\n")
    f.write("// Unicode data, (c) Unicode, Inc., used under the Unicode License v3.\n")
    f.write("// Fields: (emoji, shortcode, extra aliases (space separated), category, supports skin tones)\n")
    f.write("#[rustfmt::skip]\npub static EMOJI: &[(&str, &str, &str, u8, bool)] = &[\n")
    for emo, name, cat in entries:
        f.write('("%s","%s","%s",%d,%s),\n' % (esc(emo), code(name), ALIAS.get(name,""), cat, "true" if name in seen_tone else "false"))
    f.write("];\n")
print(len(entries), "entries", sum(1 for e in entries if e[1] in seen_tone), "toned")
if seqs_out:
    with open(seqs_out, "w", encoding="utf-8") as f:
        f.write("// @generated by crates/phoenix-app/tools/gen_emoji.py from Unicode emoji-test.txt (fully-qualified, <= E16.0).\n")
        f.write("// Unicode data, (c) Unicode, Inc., used under the Unicode License v3.\n")
        f.write("#[rustfmt::skip]\npub static SEQUENCES: &[&str] = &[\n")
        for i in range(0, len(seqs), 16):
            f.write(",".join('"%s"' % esc(e) for e in seqs[i:i+16]) + ",\n")
        f.write("];\n")
    print(len(seqs), "sequences")
